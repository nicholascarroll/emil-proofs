#!/usr/bin/env python3
"""Rebuild an ATC book's generated proofs in a world without ATC or trust tags.

Input: events.txt (ATC's expanded events as text) and the original .lisp book.
Output: a replay book that keeps the original functions and ATC's generated
encapsulate (the program constant and all its theorems), but leaves out ATC itself
and the event that writes the C files. ACL2 then has to re-prove every theorem.
"""
import re, sys
events, book, out, includes = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
s = open(events, errors="replace").read()
src = open(book).read()

def balanced(t, i):
    depth, n = 0, len(t)
    j = i
    while j < n:
        c = t[j]
        if c == '"':
            j += 1
            while t[j] != '"':
                j += 2 if t[j] == "\\" else 1
        elif c == "|":
            j += 1
            while t[j] != "|":
                j += 1
        elif c == "#" and t[j + 1] == "\\":
            j += 2
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return t[i : j + 1]
        j += 1
    raise SystemExit("unbalanced form")

i = s.find("(ENCAPSULATE NIL (EVMAC-PREPARE-PROOFS)")
if i < 0:
    raise SystemExit("generated encapsulate not found")
enc = balanced(s, i)
# Drop the event that prints and writes the C files. It isn't part of any proof.
k = enc.find("(RECORD-EXPANSION (PROGN (MAKE-EVENT")
if k < 0 or "WRITE-FILESET" not in balanced(enc, k):
    raise SystemExit("file-writing event not found")
enc = enc[:k] + enc[k + len(balanced(enc, k)):]
for bad in ("WRITE-FILESET", "MAKE-EVENT", "DEFTTAG", "SKIP-PROOFS", "DEFAXIOM", "PROGN!"):
    if bad in enc.upper():
        raise SystemExit("unexpected " + bad + " in generated encapsulate")

# Remove ATC's include-book and the (c::atc ...) call; keep everything else
src = re.sub(r'\(include-book "kestrel/c/atc/atc"[^\n]*\n', "", src)
j = src.index("(c::atc ")
src = src[:j] + balanced(src, j)[0:0] + src[j + len(balanced(src, j)):]
# A relative include means nothing from the replay directory, so make it absolute
import os
bookdir = os.path.dirname(os.path.abspath(book))
src = re.sub(r'\(include-book "(\.\./[^"]+)"\)',
             lambda m: '(include-book "%s")' % os.path.normpath(os.path.join(bookdir, m.group(1))), src)
head = '(in-package "ACL2")'
inc = "\n".join(f'(include-book "{b}" :dir :system)' for b in includes)
src = src.replace(head, head + "\n\n" + inc, 1)
# Optional events that follow the generated proofs, in the same tag-free book
extra = ""
link = os.environ.get("ATC_REPLAY_LINK")
if link:
    # Each -CORRECT theorem's own execution limit
    def limit(m):
        name = 'C::|*PROGRAM*-%s-CORRECT|' % m.group(1)
        i = enc.index("(DEFTHMD " + name)
        return re.search(r"\(>= C::LIMIT (\d+)\)", enc[i:]).group(1)
    extra = re.sub(r"@LIMIT\(([^)]+)\)", limit, open(link).read())
open(out, "w").write("; GENERATED by scripts/atc-replay.py. Do not edit or commit.\n"
                     + src + "\n" + enc + "\n" + extra + "\n")
print(f"wrote {out}: {len(enc)} bytes of generated events, "
      f"{enc.upper().count('(DEFTHM')} theorems")
